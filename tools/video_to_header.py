import cv2
import numpy as np
import sys

def convert_video_to_header(video_path, output_path="boot_frames.h", threshold=128):
    print(f"Opening {video_path}...")
    cap = cv2.VideoCapture(video_path)
    
    if not cap.isOpened():
        print("Error: Could not open video file.")
        sys.exit(1)

    frames_hex = []
    frame_count = 0

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        # 1. Convert to grayscale
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

        # 2. Resize to exactly match the OLED display (128x64)
        resized = cv2.resize(gray, (128, 64))

        # 3. Threshold to strict 1-bit monochrome (Pure Black & White)
        # Adjust the 'threshold' variable (0-255) if your video is too dark/light
        _, bw = cv2.threshold(resized, threshold, 255, cv2.THRESH_BINARY)
        
        # 4. Convert 255s to 1s for bit-packing
        bw_bits = bw // 255

        # 5. Pack every 8 horizontal pixels into 1 byte (Adafruit GFX format)
        packed = np.packbits(bw_bits, axis=-1)

        # 6. Format as C++ hex array
        hex_strings = [f"0x{b:02X}" for b in packed.flatten()]
        
        formatted_frame = "{\n"
        for i in range(0, len(hex_strings), 16):
            formatted_frame += "  " + ", ".join(hex_strings[i:i+16]) + ",\n"
        formatted_frame += "}"
        
        frames_hex.append(formatted_frame)
        frame_count += 1

    cap.release()

    # 7. Write the C++ Header File
    print(f"Processing complete. Generating {output_path} with {frame_count} frames...")
    
    with open(output_path, "w") as f:
        f.write("/* AUTO-GENERATED BY VIDEO_TO_HEADER.PY */\n")
        f.write("#ifndef BOOT_FRAMES_H\n")
        f.write("#define BOOT_FRAMES_H\n\n")
        f.write("#include <pgmspace.h>\n\n")
        f.write(f"#define TOTAL_FRAMES {frame_count}\n\n")
        
        # Write individual frame arrays
        for i, frame_data in enumerate(frames_hex):
            f.write(f"const unsigned char frame_{i}[] PROGMEM = \n")
            f.write(frame_data + ";\n\n")
            
        # Write the master pointer array
        f.write("const unsigned char* const boot_animation[] PROGMEM = {\n")
        f.write("  " + ", ".join([f"frame_{i}" for i in range(frame_count)]) + "\n")
        f.write("};\n\n")
        f.write("#endif\n")

    print(f"Success! {output_path} is ready to be included in your ESP32 project.")

if __name__ == "__main__":
    # Specify your input video file here
    INPUT_VIDEO = "boot_animation.mp4" 
    convert_video_to_header(INPUT_VIDEO)